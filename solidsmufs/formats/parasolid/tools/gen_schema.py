"""Generate ../schema_13006.py, the embedded copy of Parasolid's base schema SCH_13006.

    python gen_schema.py [path to sch_13006.s_t or .sch_txt]

Without a path it uses SolidWorks' copy (or Autodesk ATF's). Only the transmitted fields of each node
type are kept, in the compact form 'NAME field:code field:code* field:codeN' (* = variable length,
N = fixed array of N).
"""

import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.dirname(PKG))))  # the project root

from solidsmufs.formats.parasolid.schema import encode_table, parse_schema_text  # noqa: E402

DEFAULTS = (r"C:\Program Files\SOLIDWORKS Corp\SOLIDWORKS\data\pschema\sch_13006.s_t",
            r"C:\Program Files\Autodesk\*\ATF\schema\sch_13006.sch_txt")


def main(argv):
    src = argv[1] if len(argv) > 1 else next((h for p in DEFAULTS for h in sorted(glob.glob(p))), None)
    if not src:
        sys.exit("sch_13006 not found; pass its path")
    with open(src, encoding="latin-1") as fh:
        text = fh.read()
    types = parse_schema_text(text)
    for t in types.values():  # the variable-length field, if any, ends the node
        assert sum(f.var for f in t.fields) <= 1 and (not t.var or t.fields[-1].var), t.name
    table = encode_table(types)
    out = ['"""Parasolid base schema SCH_13006: {node type id: "NAME field:code ..."}, transmitted fields only.',
           "",
           "Generated by tools/gen_schema.py from " + os.path.basename(src) + "; do not edit.",
           "Codes: d int, n/w short, u byte, c char, l logical, p pointer, f double, i interval, v vector,",
           "h chart point, b box; a trailing * marks the variable-length field, a number a fixed array.",
           '"""', "", "TYPES = {"]
    for tid, line in table.items():
        out.append(f"    {tid}: {line!r},")
    out.append("}")
    dst = os.path.join(PKG, "schema_13006.py")
    with open(dst, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"{dst}: {len(table)} node types")


if __name__ == "__main__":
    main(sys.argv)
